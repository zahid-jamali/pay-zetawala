export function getPageById(id: string): PageDef | undefined {
  return PAGES.find(p => p.id === id);
}

export function getPageByPath(path: string): PageDef | undefined {
  const normalized = path.endsWith('/') ? path : `${path}/`;
  return PAGES.find(p => p.path === normalized);
}

export function getPagesByCountry(country: CountryCode): PageDef[] {
  return PAGES.filter(p => p.country === country);
}

export function getRelatedPages(pageId: string): PageDef[] {
  const current = getPageById(pageId);
  if (!current) return [];
  return current.relatedIds
    .map(id => getPageById(id))
    .filter((p): p is PageDef => p !== undefined);
}
